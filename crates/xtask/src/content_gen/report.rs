//! `text_parsed_fields.md`: the rules the engine decides by parsing free text, and what the
//! generator did with each (a typed column where the mapping is mechanical, else a TODO).

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::Value;

use super::Ctx;
use super::spec::Cat;

fn text<'a>(rec: &'a super::Rec, field: &str) -> Option<&'a str> {
    rec.fields.get(field).and_then(Value::as_str)
}

/// Distinct values of a field with the ids that carry each, most frequent first.
fn grouped<'a>(ctx: &'a Ctx, key: &str, field: &str) -> Vec<(&'a str, Vec<&'a str>)> {
    let mut by: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for rec in ctx.records(key) {
        if let Some(v) = text(rec, field) {
            by.entry(v.trim()).or_default().push(rec.id.as_str());
        }
    }
    let mut out: Vec<_> = by.into_iter().collect();
    out.sort_by(|a, b| b.1.len().cmp(&a.1.len()).then(a.0.cmp(b.0)));
    out
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

#[must_use]
#[allow(clippy::too_many_lines)]
pub fn text_parsed(ctx: &Ctx, cats: &[Cat]) -> String {
    let has = |k: &str| cats.iter().any(|c| c.key == k);
    let mut out = String::new();
    out.push_str(
        "<!-- @generated by `cargo xtask gen-cards`. DO NOT EDIT. -->\n\n\
         # Text-parsed rules\n\n\
         Rules the engine decides by parsing a free-text field of the corpus\n\
         (docs/CARD_USAGE_AUDIT.md, issues I06-I10), and what the generator does with each. **Typed**:\n\
         the engine's rule is a mechanical function of the text, so the generator applies it and the\n\
         core gets a typed column. **TODO**: the mapping is engine knowledge or needs a decision, so\n\
         nothing is guessed; the values to map are listed here instead.\n\n",
    );

    if has("action_cards") {
        let windows = grouped(ctx, "action_cards", "window");
        let _ = writeln!(
            out,
            "## action_cards.window\n\n\
             - **Typed**: `ActionCardData::component_action` = the trimmed window is exactly `Action`\n\
               (`action_cards.rs`, `keleres.rs`).\n\
             - **TODO**: the reaction timing. `reactions::window_table` binds each printed sentence to an\n\
               engine event; that table is engine code, not content. Once the core exists, a `Timing`\n\
               enum replaces it and each card gets a `timing` column (by hand or from a committed\n\
               sentence -> timing file). {} distinct sentences:\n",
            windows.len()
        );
        out.push_str("| window | cards |\n|---|---|\n");
        for (window, ids) in &windows {
            let _ = writeln!(out, "| {} | {} |", cell(window), ids.join(", "));
        }
        out.push('\n');
    }

    if has("agendas") {
        let _ = writeln!(
            out,
            "## agendas.target\n\n\
             - **Typed**: `AgendaData::elects` (`AgendaElects`) = the text up to the first `(`, without\n\
               `Elect`; `For/Against` when it does not start with `Elect` (`vote::outcomes`). The engine's\n\
               `contains(\"Player\")` / `contains(\"Planet\")` / `Non-Home` / `Law` checks become a `match` on it.\n\
             - **TODO**: the parenthetical rule (\"if there are no laws in play, discard this card ...\")\n\
               is not typed; Covert Legislation's target is a rules sentence and types as `For/Against`,\n\
               exactly as the engine reads it today (audit I04).\n"
        );
        out.push_str("| target | elects | agendas |\n|---|---|---|\n");
        for (target, ids) in grouped(ctx, "agendas", "target") {
            let elects = super::spec::agenda_elects(target)
                .ok()
                .flatten()
                .unwrap_or_default();
            let _ = writeln!(
                out,
                "| {} | `{elects}` | {} |",
                cell(target),
                ids.join(", ")
            );
        }
        out.push('\n');
    }

    if has("leaders") {
        let _ = writeln!(
            out,
            "## leaders.abilityWindow\n\n\
             - **Typed**: `LeaderData::window` (`LeaderWindow`): `Action` when the trimmed window starts\n\
               with `ACTION`, `ActionPhase` for `During the action phase:`, else `Other`\n\
               (`leaders::is_action_window`, `leaders::uses_the_action`).\n"
        );
        let mut counts: BTreeMap<String, usize> = BTreeMap::new();
        for rec in ctx.records("leaders") {
            if let Some(w) = text(rec, "abilityWindow") {
                let k = super::spec::leader_window(w)
                    .ok()
                    .flatten()
                    .unwrap_or_default();
                *counts.entry(k).or_default() += 1;
            }
        }
        for (k, n) in counts {
            let _ = writeln!(out, "  - `{k}`: {n} leaders");
        }
        out.push('\n');
    }

    if has("technologies") {
        let blocked: Vec<&str> = ctx
            .records("technologies")
            .iter()
            .filter(|r| {
                text(r, "text")
                    .is_some_and(|t| t.to_ascii_lowercase().contains("cannot be researched"))
            })
            .map(|r| r.id.as_str())
            .collect();
        let _ = writeln!(
            out,
            "## technologies.text\n\n\
             - **Typed**: `TechnologyData::researchable` = false when the text contains\n\
               `cannot be researched` (`technology.rs`, `deepwrought.rs`): {}.\n",
            blocked.join(", ")
        );
    }

    if has("strategy_cards") {
        let _ = writeln!(
            out,
            "## strategy_cards.name\n\n\
             - **Typed**: `StrategyCardData::kind` (`StrategyCardKind`) = the printed name, on which\n\
               `strategy_cards.rs` dispatches.\n\
             - **TODO**: the printing variant. The engine special-cases `te4construction` and\n\
               `te6warfare` by id, and `base2` / `pok2diplomacy` print different Diplomacy texts but\n\
               share a name (audit I09). Whether a variant tag (`Base`, `Codex`, `ThundersEdge`) is a\n\
               column or the id itself is the discriminator is for the core to decide.\n"
        );
        out.push_str("| kind | printings |\n|---|---|\n");
        for (name, ids) in grouped(ctx, "strategy_cards", "name") {
            let _ = writeln!(out, "| {name} | {} |", ids.join(", "));
        }
        out.push('\n');
    }

    if has("factions") {
        let _ = writeln!(
            out,
            "## factions.startingFleet\n\n\
             - **TODO**: the opening fleet is a text (`\"cv, cr, 2 ff, 4 inf n, pds n, sd n\"`) read by\n\
               `factions::parse_fleet`: counts, unit `asyncId` codes and planet letter codes resolved\n\
               against the home planets. Typing it means a `[(Unit, count, Option<Planet>)]` column;\n\
               the grammar (and its unit/planet resolution) is engine code, so it stays text for now\n\
               (adapter `FactionText::starting_fleet`).\n"
        );
    }

    if has("units") {
        let support: Vec<&str> = ctx
            .records("units")
            .iter()
            .filter(|r| {
                text(r, "ability").is_some_and(|t| {
                    let l = t.to_ascii_lowercase();
                    l.find("up to ").is_some_and(|i| l[i..].contains("fighter"))
                })
            })
            .map(|r| r.id.as_str())
            .collect();
        let _ = writeln!(
            out,
            "## units.ability\n\n\
             - **TODO**: `UnitType::fighter_support` reads \"up to N ... fighter\" out of the printed\n\
               ability (space docks, Dimensional Tear). Candidates by that rule: {}. A typed\n\
               `fighter_support: u8` column needs the rule confirmed per unit first.\n\
             - Not text, but noted: `UnitType::is_ground_force` decides by base type plus two Titans\n\
               ids, not by the printed `isGroundForce` flag (the core column carries the flag as printed).\n",
            support.join(", ")
        );
    }
    out
}
