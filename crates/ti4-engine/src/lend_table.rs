//! The bail table (docs/todo/D2-prereqs.md D2-5 item 5): every window label the core bails out of in the golden dual,
//! and the slices its string body writes. After the flip such a label is a `reverse_lend::with_string` wrapper whose
//! footprint is this entry; an unknown label lends `Footprint::ALL`, so correctness never depends on the table.
//!
//! **How the table is made.** With `TI4_BAIL_PROBE=FILE` set, `dual::run_dual_window` appends one line
//! `label<TAB>slice,slice,..` to FILE every time the core bows out of a window (the slices whose fields the string body
//! changed between the copy the core would have run on and the state the string left; [`probe`]). A golden dual run
//! (sharded: append is atomic per line) writes the observations; `cargo run -p ti4-engine-core-bridge --bin bail_table
//! FILE..` merges them (union per label) and prints the rows of [`BAILS`]. Observed writes are a **lower bound**: a
//! window that bails in a position where its body happens not to write a slice still may elsewhere, so the footprint
//! audit of `reverse_lend` is the safety net and entries are widened by hand.
//!
//! [`BAILS`] is empty on this branch: the observation run is a golden dual (heavy) and waits for the end of D1.

use std::collections::BTreeMap;

use ti4_engine_core::state::{Slice, SliceSet};
use ti4_model::state::GameState;

use crate::dual::WindowCounts;

/// One window label the core bails out of.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Bail {
    /// The `dual_window!` label.
    pub label: &'static str,
    /// What the string body may write (the footprint's writes).
    pub writes: SliceSet,
    /// What it reads (a superset of `writes` is fine; `SliceSet::ALL` when unknown).
    pub reads: SliceSet,
    /// The issue ids of `docs/ENGINE_KNOWN_ISSUES.md` that explain the bail (`"B12-bail-02"`).
    pub ids: &'static [&'static str],
    /// The test that pins the bail.
    pub test: &'static str,
}

/// The table. Generated by `bail_table` from a golden dual, then checked by hand.
pub const BAILS: &[Bail] = &[];

/// The label of a report key: the windows map also holds `"label [bail: why]"` rows for the reasons.
#[must_use]
pub fn label_of(key: &str) -> &str {
    key.split(" [bail:").next().unwrap_or(key)
}

/// The labels of `windows` that bailed at least once and have no entry in `table`.
#[must_use]
pub fn missing_entries(windows: &BTreeMap<String, WindowCounts>, table: &[Bail]) -> Vec<String> {
    let mut missing: Vec<String> = windows
        .iter()
        .filter(|(_, w)| w.bailed > 0)
        .map(|(key, _)| label_of(key).to_owned())
        .filter(|label| !table.iter().any(|b| b.label == label))
        .collect();
    missing.sort();
    missing.dedup();
    missing
}

/// The entries of `table` whose label no window of `windows` ever bailed at (a stale entry hides a port that landed).
#[must_use]
pub fn stale_entries(windows: &BTreeMap<String, WindowCounts>, table: &[Bail]) -> Vec<&'static str> {
    table
        .iter()
        .filter(|b| !windows.iter().any(|(key, w)| w.bailed > 0 && label_of(key) == b.label))
        .map(|b| b.label)
        .collect()
}

/// The slices of `after` that differ from `before`, by the fields of the serialised state.
#[must_use]
pub fn changed_slices(before: &GameState, after: &GameState) -> SliceSet {
    let mut set = SliceSet::EMPTY;
    let (Ok(serde_json::Value::Object(a)), Ok(serde_json::Value::Object(b))) = (serde_json::to_value(before), serde_json::to_value(after)) else {
        return set;
    };
    for key in a.keys().chain(b.keys()) {
        if a.get(key) != b.get(key) {
            set.insert(crate::core_sync::materialize::slice_of_field(key));
        }
    }
    set
}

/// A line of the probe file: `label<TAB>slice,slice,..` (`-` for none).
#[must_use]
pub fn probe_line(label: &str, writes: SliceSet) -> String {
    let names: Vec<String> = Slice::ALL.iter().filter(|s| writes.has(**s)).map(|s| format!("{s:?}")).collect();
    format!("{label}\t{}", if names.is_empty() { "-".to_owned() } else { names.join(",") })
}

/// The probe lines merged: per label the union of the slices.
#[must_use]
pub fn merge_probe<'a>(lines: impl IntoIterator<Item = &'a str>) -> BTreeMap<String, SliceSet> {
    let mut out: BTreeMap<String, SliceSet> = BTreeMap::new();
    for line in lines {
        let Some((label, slices)) = line.split_once('\t') else { continue };
        let entry = out.entry(label.to_owned()).or_insert(SliceSet::EMPTY);
        for name in slices.split(',').filter(|n| *n != "-") {
            if let Some(slice) = Slice::ALL.iter().find(|s| format!("{s:?}") == name) {
                entry.insert(*slice);
            }
        }
    }
    out
}

/// The Rust source of the rows [`BAILS`] needs for `observed`.
#[must_use]
pub fn render_table(observed: &BTreeMap<String, SliceSet>) -> String {
    let mut out = String::from("pub const BAILS: &[Bail] = &[\n");
    for (label, writes) in observed {
        let names: Vec<String> = Slice::ALL.iter().filter(|s| writes.has(**s)).map(|s| format!("Slice::{s:?}")).collect();
        out.push_str(&format!(
            "    Bail {{ label: {label:?}, writes: SliceSet::of(&[{}]), reads: SliceSet::ALL, ids: &[], test: \"\" }},\n",
            names.join(", ")
        ));
    }
    out.push_str("];\n");
    out
}

/// Append the probe line of `label` to the file `path` (created when missing).
pub fn probe_to(path: &std::path::Path, label: &str, pre: &GameState, post: &GameState) {
    use std::io::Write as _;
    let line = probe_line(label, changed_slices(pre, post));
    if let Ok(mut file) = std::fs::OpenOptions::new().create(true).append(true).open(path) {
        let _ = writeln!(file, "{line}");
    }
}

/// `TI4_BAIL_PROBE`: record the slices a window's string body wrote when the core bowed out of it. `pre` is the copy the
/// core would have run on, `post` the state the string left. A no-op unless the variable names a file (never in the
/// browser build).
// mutants:skip (the environment is read once per process; `probe_to` carries the behaviour and is tested)
pub fn probe(label: &str, pre: &GameState, post: &GameState) {
    #[cfg(not(target_arch = "wasm32"))]
    {
        use std::sync::OnceLock;
        static FILE: OnceLock<Option<String>> = OnceLock::new();
        let Some(path) = FILE.get_or_init(|| std::env::var("TI4_BAIL_PROBE").ok().filter(|p| !p.is_empty())) else { return };
        probe_to(std::path::Path::new(path), label, pre, post);
    }
    #[cfg(target_arch = "wasm32")]
    let _ = (label, pre, post);
}

#[cfg(test)]
mod tests {
    use super::*;

    fn counts(compared: u64, bailed: u64) -> WindowCounts {
        WindowCounts { compared, bailed }
    }

    const ENTRY: Bail = Bail { label: "combat::roll", writes: SliceSet::of(&[Slice::Transient]), reads: SliceSet::ALL, ids: &["B12-bail-02"], test: "t" };

    #[test]
    fn a_bailing_label_without_an_entry_is_missing_whatever_its_reason_row() {
        let mut windows = BTreeMap::new();
        windows.insert("combat::roll".to_owned(), counts(5, 1));
        windows.insert("combat::roll [bail: nested (x)]".to_owned(), counts(0, 1));
        windows.insert("leaders::xxcha".to_owned(), counts(3, 0));
        windows.insert("trade::deal [bail: diplomacy]".to_owned(), counts(0, 2));
        assert_eq!(missing_entries(&windows, &[]), vec!["combat::roll".to_owned(), "trade::deal".to_owned()]);
        assert_eq!(missing_entries(&windows, &[ENTRY]), vec!["trade::deal".to_owned()]);
    }

    #[test]
    fn an_entry_nobody_bails_at_any_more_is_stale() {
        let mut windows = BTreeMap::new();
        windows.insert("combat::roll".to_owned(), counts(5, 0));
        assert_eq!(stale_entries(&windows, &[ENTRY]), vec!["combat::roll"], "compared only: the port landed");
        windows.insert("combat::roll".to_owned(), counts(5, 2));
        assert!(stale_entries(&windows, &[ENTRY]).is_empty());
    }

    #[test]
    fn a_label_that_bailed_exactly_once_is_not_stale() {
        let mut windows = BTreeMap::new();
        windows.insert("combat::roll".to_owned(), counts(0, 1));
        assert!(stale_entries(&windows, &[ENTRY]).is_empty());
    }

    #[test]
    fn the_probe_appends_one_line_per_bail_to_its_file() {
        let dir = std::env::temp_dir().join(format!("ti4-bail-probe-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let file = dir.join("probe.tsv");
        let before = crate::fixtures::game(&["a", "b"]);
        let mut after = before.clone();
        after.players[0].trade_goods += 1;
        probe_to(&file, "w1", &before, &after);
        probe_to(&file, "w2", &before, &before);
        let text = std::fs::read_to_string(&file).unwrap();
        assert_eq!(text, "w1\tPlayers\nw2\t-\n");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn probe_lines_merge_by_union_and_render_as_rows() {
        let a = probe_line("w", SliceSet::of(&[Slice::Players, Slice::Board]));
        let b = probe_line("w", SliceSet::of(&[Slice::Board, Slice::Marks]));
        let none = probe_line("quiet", SliceSet::EMPTY);
        assert_eq!(a, "w\tPlayers,Board");
        assert_eq!(none, "quiet\t-");
        let merged = merge_probe([a.as_str(), b.as_str(), none.as_str(), "garbage line"]);
        assert_eq!(merged["w"], SliceSet::of(&[Slice::Players, Slice::Board, Slice::Marks]));
        assert_eq!(merged["quiet"], SliceSet::EMPTY);
        let rows = render_table(&merged);
        assert!(rows.contains("Bail { label: \"w\", writes: SliceSet::of(&[Slice::Players, Slice::Board, Slice::Marks])"), "{rows}");
    }

    #[test]
    fn the_changed_slices_are_those_of_the_fields_that_differ() {
        let before = crate::fixtures::game(&["a", "b"]);
        let mut after = before.clone();
        after.players[0].trade_goods += 1;
        after.round += 1;
        assert_eq!(changed_slices(&before, &after), SliceSet::of(&[Slice::Players, Slice::Meta]));
        assert_eq!(changed_slices(&before, &before), SliceSet::EMPTY);
    }

    #[test]
    fn the_table_has_no_duplicate_labels() {
        let mut labels: Vec<&str> = BAILS.iter().map(|b| b.label).collect();
        labels.sort_unstable();
        let n = labels.len();
        labels.dedup();
        assert_eq!(n, labels.len());
    }
}
