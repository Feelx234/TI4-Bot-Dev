/// An emitted event: its trace-local id, a typed kind and the typed payload.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EventRec {
    pub id: u64,
    pub kind: EventKind,
    pub payload: Payload,
    pub cancelled: bool,
}

/// Why dice were rolled (`Roll.reason`, about 25 literals). B1 extends the closed list; `Other` is an
/// adapter-interned reason text.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum RollPurpose {
    SpaceCombat,
    GroundCombat,
    AntiFighterBarrage,
    SpaceCannon,
    Bombardment,
    Reroll,
    /// Rolled by an ability (the slot of `kernel::ability::Slot`).
    Ability(u16),
    Other(Code),
}

/// One roll of a group of dice (`dice::Roll`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RollRec {
    pub purpose: RollPurpose,
    pub owner: Option<Seat>,
    pub unit: Option<Unit>,
    pub planet: Option<Planet>,
    pub scene: Option<System>,
    pub hits_on: Option<u8>,
    pub faces: SmallList<u8, 8>,
    /// Bit `i`: die `i` replaced by a reroll.
    pub rerolled: u64,
}

/// `vp_ledger` row: (player, change, reason).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct VpRec {
    pub player: Seat,
    pub delta: i32,
    pub reason: LedgerReason,
}

/// `RelicGainRecord`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RelicRec {
    pub round: u32,
    pub player: Seat,
    pub relic: Relic,
    pub victory_points: i32,
}

#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Ledger {
    /// The ordered emission queue (`Game::events`): typed events mirrored from the resolver and plain events, in the order
    /// the string pushes them (package P1; `state/plain.rs`). Output only: no codec loads or stores it.
    pub events: Log<Emit>,
    pub dice: Log<RollRec>,
    pub vp: Log<VpRec>,
    pub relics: Log<RelicRec>,
}
