//! Generates the typed content tables of the raw core from the corpus (docs/ENGINE_CORE.md,
//! "Content tables").
//!
//! The corpus is read with `ti4-content`'s own parser (a build dependency), so a flag, a planet list
//! or a lane table means exactly what it means to the string engine. Ids are numbered in the text
//! order of the id (`str` byte order, the order of every `BTreeMap<String, _>` in the engine), so
//! comparing two indices answers what comparing the two strings answers and iterating a bitset in
//! index order visits the ids in the order a `BTreeSet<String>` would.
//!
//! Two files are written to `$OUT_DIR`:
//! - `tables.rs`: counts and typed records (flags, wormhole masks, source bit, lanes, planets). No
//!   text. Included by the core.
//! - `names.rs`: the id text of every index, in the same order. Included only with the `names`
//!   feature, which only the adapter enables.

use std::collections::BTreeSet;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use strum::IntoEnumIterator;
use ti4_content::ContentStore;
use ti4_content::galaxy::{Planet, System};
use ti4_content::units::UnitType;
use ti4_model::content_types::{ContentType, Source, SourceSet};

/// Bit of a record's source tag: the position of its `Source` variant (`Source::iter()` order).
/// The adapter computes a scope mask the same way. `0` for an untagged record (never in scope).
fn source_bit(in_sources: impl Fn(SourceSet) -> bool) -> u32 {
    Source::iter()
        .enumerate()
        .find(|(_, s)| in_sources(SourceSet::only(*s)))
        .map_or(0, |(i, _)| 1u32 << i)
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let store = ContentStore::embedded();
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());

    // -- systems, sorted by id text ------------------------------------------------------------
    let mut systems: Vec<(&str, System<'_>)> = store
        .records(ContentType::Systems)
        .iter()
        .filter_map(|r| r.id().map(|id| (id, System::new(r))))
        .collect();
    systems.sort_by(|a, b| a.0.cmp(b.0));
    let system_ix = |id: &str| systems.binary_search_by(|(s, _)| (*s).cmp(id)).ok();

    // Wormhole kinds of the corpus, sorted: bit k is the k-th kind in text order.
    let kinds: Vec<String> = systems
        .iter()
        .flat_map(|(_, s)| s.wormholes().into_iter().map(str::to_owned))
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();
    assert!(kinds.len() <= 8, "wormhole kinds fit a u8");

    // -- planets -------------------------------------------------------------------------------
    let mut planets: Vec<(&str, Planet<'_>)> = store
        .records(ContentType::Planets)
        .iter()
        .filter_map(|r| r.id().map(|id| (id, Planet::new(r))))
        .collect();
    planets.sort_by(|a, b| a.0.cmp(b.0));
    let planet_ix = |id: &str| planets.binary_search_by(|(p, _)| (*p).cmp(id)).ok();

    // -- unit types ----------------------------------------------------------------------------
    let mut units: Vec<(&str, UnitType<'_>)> = store
        .by_id_in_sources(ContentType::Units, SourceSet::all())
        .map(|(id, r)| (id, UnitType::new(r)))
        .collect();
    // Records without a source tag are in no scope; listed anyway so every id has an index.
    for r in store.records(ContentType::Units) {
        if let Some(id) = r.id()
            && !units.iter().any(|(u, _)| *u == id)
        {
            units.push((id, UnitType::new(r)));
        }
    }
    units.sort_by(|a, b| a.0.cmp(b.0));

    let mut t = String::new();
    writeln!(t, "// @generated by ti4-engine-core/build.rs from the ti4-content corpus.").unwrap();
    writeln!(t, "pub const SYSTEM_COUNT: usize = {};", systems.len()).unwrap();
    writeln!(t, "pub const PLANET_COUNT: usize = {};", planets.len()).unwrap();
    writeln!(t, "pub const UNIT_COUNT: usize = {};", units.len()).unwrap();
    writeln!(t, "pub const WORMHOLE_KIND_COUNT: usize = {};", kinds.len()).unwrap();
    for (bit, kind) in kinds.iter().enumerate() {
        writeln!(t, "pub const WH_{kind}: u8 = 1 << {bit};").unwrap();
    }
    writeln!(t, "pub static SYSTEMS: [SystemData; SYSTEM_COUNT] = [").unwrap();
    for (id, s) in &systems {
        let mut flags = Vec::new();
        for (on, name) in [
            (s.is_nebula(), "NEBULA"),
            (s.is_supernova(), "SUPERNOVA"),
            (s.is_asteroid_field(), "ASTEROID_FIELD"),
            (s.is_gravity_rift(), "GRAVITY_RIFT"),
            (s.is_hyperlane(), "HYPERLANE"),
            (s.is_scar(), "SCAR"),
            // `Galaxy::wormhole_kinds`: Nexus Sovereignty suppresses ids starting with "82".
            (id.starts_with("82"), "NEXUS"),
        ] {
            if on {
                flags.push(format!("SystemFlags::{name}"));
            }
        }
        let flags = if flags.is_empty() {
            "0".to_owned()
        } else {
            flags.join(" | ")
        };
        let wormholes: Vec<String> = s.wormholes().iter().map(|k| format!("WH_{k}")).collect();
        let wormholes = if wormholes.is_empty() {
            "0".to_owned()
        } else {
            wormholes.join(" | ")
        };
        let lanes = match (s.is_hyperlane(), ti4_content::hyperlane::lanes_of(id)) {
            (true, Some(l)) => format!(
                "Some(&[{}])",
                l.iter()
                    .map(|(a, b)| format!("({a}, {b})"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
            _ => "None".to_owned(),
        };
        let mut planet_list = Vec::new();
        for p in s.planets() {
            // A system lists a planet the planet corpus does not carry: no index, left out (the
            // movement slice does not read planets; the adapter checks the lists are complete).
            if let Some(ix) = planet_ix(p) {
                planet_list.push(format!("PlanetIx({ix})"));
            }
        }
        let source = source_bit(|set| s.record().in_sources(set));
        writeln!(
            t,
            "    SystemData {{ flags: {flags}, wormholes: {wormholes}, source: {source}, lanes: {lanes}, planets: &[{}] }},",
            planet_list.join(", ")
        )
        .unwrap();
    }
    writeln!(t, "];").unwrap();

    writeln!(t, "pub static PLANETS: [PlanetData; PLANET_COUNT] = [").unwrap();
    for (_, p) in &planets {
        let system = p
            .system_id()
            .and_then(system_ix)
            .map_or_else(|| "None".to_owned(), |ix| format!("Some(SystemIx({ix}))"));
        let source = source_bit(|set| p.record().in_sources(set));
        writeln!(
            t,
            "    PlanetData {{ system: {system}, resources: {}, influence: {}, source: {source}, space_station: {} }},",
            p.resources(),
            p.influence(),
            p.is_space_station()
        )
        .unwrap();
    }
    writeln!(t, "];").unwrap();

    writeln!(t, "pub static UNITS: [UnitData; UNIT_COUNT] = [").unwrap();
    for (_, u) in &units {
        let source = source_bit(|set| u.record().in_sources(set));
        writeln!(
            t,
            "    UnitData {{ is_ship: {}, moves_as_ship: {}, source: {source} }},",
            u.is_ship(),
            u.moves_as_ship()
        )
        .unwrap();
    }
    writeln!(t, "];").unwrap();
    fs::write(out.join("tables.rs"), t).unwrap();

    // -- names (adapter only) ------------------------------------------------------------------
    let mut n = String::new();
    writeln!(n, "// @generated by ti4-engine-core/build.rs. Index -> id text, sorted.").unwrap();
    let list = |name: &str, ids: Vec<&str>, n: &mut String| {
        writeln!(n, "pub static {name}: [&str; {}] = [", ids.len()).unwrap();
        for id in ids {
            writeln!(n, "    {id:?},").unwrap();
        }
        writeln!(n, "];").unwrap();
    };
    list("SYSTEM_NAMES", systems.iter().map(|(id, _)| *id).collect(), &mut n);
    list("PLANET_NAMES", planets.iter().map(|(id, _)| *id).collect(), &mut n);
    list("UNIT_NAMES", units.iter().map(|(id, _)| *id).collect(), &mut n);
    list(
        "WORMHOLE_KIND_NAMES",
        kinds.iter().map(String::as_str).collect(),
        &mut n,
    );
    let sources: Vec<String> = Source::iter().map(|s| s.to_string()).collect();
    list(
        "SOURCE_NAMES",
        sources.iter().map(String::as_str).collect(),
        &mut n,
    );
    fs::write(out.join("names.rs"), n).unwrap();
}
