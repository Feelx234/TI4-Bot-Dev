//! ti4-mutants: a source rewriter that puts MANY mutants of chosen Rust files into ONE build, behind a
//! runtime switch (env var `TI4_MUTANT=<id>`, 0 or unset = the original program). See docs/ENGINE_COMPUTE.md.
//!
//!   ti4-mutants gen   --orig ROOT --dest ROOT --points points.json [--disable FILE] [--kinds LIST]
//!                     [--fn NAMES] [--lines S-E] FILE...        (FILE relative to ROOT)
//!   ti4-mutants prune --points points.json --dest ROOT --disable FILE [--all] < cargo-json-messages
//!
//! `gen` reads FILEs from the pristine tree ROOT, writes the mutated text to the same relative path in the
//! scratch tree, adds `src/__mutant.rs` (the switch) and `mod __mutant;` to the crate roots, and writes
//! points.json (one entry per mutation point, with line/col, kind and the original/mutated expression).
//! Nothing here touches the pristine tree. `prune` reads `cargo --message-format=json` output of a failed
//! build and disables the mutation points that caused compile errors (appends their ids to FILE).
use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fs;
use std::path::{Path, PathBuf};

use proc_macro2::{LineColumn, TokenTree};
use quote::ToTokens;
use serde_json::{Value, json};
use syn::visit::Visit;
use syn::{BinOp, Expr, ExprBinary, ImplItemFn, ItemFn, Lit, ReturnType, Type};

const RT: &str = "crate::__mutant";

const RUNTIME: &str = r#"//! Generated by tools/mutants (docs/ENGINE_COMPUTE.md). Never committed: it exists only in the scratch tree.
//! The switch of the mutants: env var TI4_MUTANT=<id>; 0 or unset = the original program.
use std::sync::atomic::{AtomicU32, Ordering::Relaxed};
const UNINIT: u32 = u32::MAX;
static ACTIVE: AtomicU32 = AtomicU32::new(UNINIT);
#[cold]
fn init() -> u32 {
    let v = std::env::var("TI4_MUTANT").ok().and_then(|s| s.trim().parse().ok()).unwrap_or(0);
    ACTIVE.store(v, Relaxed);
    v
}
#[inline]
pub fn active() -> u32 {
    let a = ACTIVE.load(Relaxed);
    if a == UNINIT { init() } else { a }
}
#[inline]
pub fn on(id: u32) -> bool {
    active() == id
}
/// Condition with the mutant "negated".
#[inline]
pub fn not(id: u32, c: bool) -> bool {
    c ^ on(id)
}
/// `a && b`, mutant `a || b`.
#[inline]
pub fn and(id: u32, a: bool, b: impl FnOnce() -> bool) -> bool {
    if on(id) { a || b() } else { a && b() }
}
/// `a || b`, mutant `a && b`.
#[inline]
pub fn or(id: u32, a: bool, b: impl FnOnce() -> bool) -> bool {
    if on(id) { a && b() } else { a || b() }
}
"#;

#[derive(Clone)]
enum Tmpl {
    Ins(String),
    Bin { a: (usize, usize), b: (usize, usize), orig: &'static str, mutd: &'static str, by_ref: bool },
    Assign { lhs: (usize, usize), rhs: (usize, usize), orig: &'static str, mutd: &'static str },
    Logic { a: (usize, usize), b: (usize, usize), is_and: bool },
    Cond,
    Lit(String, String),
}

#[derive(Clone)]
struct Point {
    id: u32,
    seq: usize,
    kind: &'static str,
    file: String,
    s: usize,
    e: usize,
    tmpl: Tmpl,
    line: usize,
    col: usize,
    func: String,
    desc: String,
    orig: String,
    mutated: String,
}

struct Src {
    text: String,
    line_starts: Vec<usize>,
}
impl Src {
    fn new(text: String) -> Src {
        let mut line_starts = vec![0];
        for (i, b) in text.bytes().enumerate() {
            if b == b'\n' {
                line_starts.push(i + 1);
            }
        }
        Src { text, line_starts }
    }
    fn off(&self, lc: LineColumn) -> usize {
        let ls = self.line_starts[(lc.line - 1).min(self.line_starts.len() - 1)];
        let rest = &self.text[ls..];
        let line_end = rest.find('\n').unwrap_or(rest.len());
        let line = &rest[..line_end];
        ls + line.char_indices().nth(lc.column).map(|(i, _)| i).unwrap_or(line.len())
    }
    fn line_of(&self, off: usize) -> (usize, usize) {
        let l = match self.line_starts.binary_search(&off) {
            Ok(i) => i,
            Err(i) => i - 1,
        };
        (l + 1, self.text[self.line_starts[l]..off].chars().count() + 1)
    }
    fn line_text(&self, line: usize) -> &str {
        let s = self.line_starts[line - 1];
        let e = self.line_starts.get(line).copied().unwrap_or(self.text.len());
        &self.text[s..e]
    }
    fn range<T: ToTokens>(&self, t: &T) -> Option<(usize, usize)> {
        let toks: Vec<TokenTree> = t.to_token_stream().into_iter().collect();
        let first = toks.first()?;
        let last = toks.last()?;
        let (s, e) = (self.off(first.span().start()), self.off(last.span().end()));
        (s < e && e <= self.text.len()).then_some((s, e))
    }
}

fn is_cfg_test(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().any(|a| {
        let p = a.path();
        (p.is_ident("cfg") && a.meta.to_token_stream().to_string().split(|c: char| !c.is_alphanumeric() && c != '_').any(|w| w == "test"))
            || p.is_ident("test")
    })
}

fn contains_let(e: &Expr) -> bool {
    match e {
        Expr::Let(_) => true,
        Expr::Binary(b) => contains_let(&b.left) || contains_let(&b.right),
        Expr::Paren(p) => contains_let(&p.expr),
        _ => false,
    }
}

#[derive(Default)]
struct Ctl(bool);
impl<'a> Visit<'a> for Ctl {
    fn visit_expr_return(&mut self, _: &'a syn::ExprReturn) {
        self.0 = true;
    }
    fn visit_expr_break(&mut self, _: &'a syn::ExprBreak) {
        self.0 = true;
    }
    fn visit_expr_continue(&mut self, _: &'a syn::ExprContinue) {
        self.0 = true;
    }
    fn visit_expr_try(&mut self, _: &'a syn::ExprTry) {
        self.0 = true;
    }
    fn visit_expr_await(&mut self, _: &'a syn::ExprAwait) {
        self.0 = true;
    }
    fn visit_expr_let(&mut self, _: &'a syn::ExprLet) {
        self.0 = true;
    }
}
fn has_ctl(e: &Expr) -> bool {
    let mut c = Ctl::default();
    c.visit_expr(e);
    c.0
}

struct Opts {
    kinds: BTreeSet<String>,
    fns: Vec<String>,
    lines: Option<(usize, usize)>,
}

struct Collect<'o> {
    src: &'o Src,
    file: String,
    o: &'o Opts,
    next_id: &'o mut u32,
    pts: Vec<Point>,
    func: Vec<String>,
    impl_ty: Vec<String>,
    in_fn: usize,
    skip_fn: usize,
}

fn flat(s: &str, n: usize) -> String {
    let t = s.split_whitespace().collect::<Vec<_>>().join(" ");
    if t.chars().count() > n { format!("{}...", t.chars().take(n).collect::<String>()) } else { t }
}

impl<'o> Collect<'o> {
    fn want(&self, k: &str) -> bool {
        self.o.kinds.contains(k)
    }
    fn snip(&self, r: (usize, usize)) -> &str {
        &self.src.text[r.0..r.1]
    }
    fn fname(&self) -> String {
        match (self.impl_ty.last(), self.func.last()) {
            (Some(t), Some(f)) if !t.is_empty() => format!("{t}::{f}"),
            (_, Some(f)) => f.clone(),
            _ => String::new(),
        }
    }
    fn push(&mut self, kind: &'static str, s: usize, e: usize, tmpl: Tmpl, desc: String, orig: String, mutated: String) {
        let (line, col) = self.src.line_of(s);
        if let Some((a, b)) = self.o.lines {
            if line < a || line > b {
                return;
            }
        }
        if self.src.line_text(line).contains("mutants:skip") {
            return;
        }
        if !self.o.fns.is_empty() {
            let f = self.fname();
            if !self.o.fns.iter().any(|n| f.contains(n.as_str())) {
                return;
            }
        }
        *self.next_id += 1;
        let id = *self.next_id;
        let seq = self.pts.len();
        let func = self.fname();
        self.pts.push(Point { id, seq, kind, file: self.file.clone(), s, e, tmpl, line, col, func, desc, orig, mutated });
    }

    fn fn_like(&mut self, attrs: &[syn::Attribute], sig: &syn::Signature, block: &syn::Block) {
        if is_cfg_test(attrs) || sig.constness.is_some() {
            return;
        }
        let (sl, _) = self.src.line_of(self.src.range(&sig.fn_token).map(|r| r.0).unwrap_or(0));
        let skip = (sl.saturating_sub(1)..=sl).filter(|l| *l >= 1).any(|l| self.src.line_text(l).contains("mutants:skip"))
            || attrs.iter().any(|a| a.path().segments.last().is_some_and(|s| s.ident == "skip") && a.path().segments.len() == 2);
        if skip {
            return;
        }
        self.func.push(sig.ident.to_string());
        self.in_fn += 1;
        if self.want("body") && sig.asyncness.is_none() {
            let open = self.src.off(block.brace_token.span.open().end());
            let (rv, unit) = ret_values(&sig.output);
            if !(unit && block.stmts.is_empty()) {
                for (label, code) in rv {
                    let id_next = *self.next_id + 1;
                    let text = format!(" if {RT}::on({id_next}) {{ return{}; }}", if code.is_empty() { String::new() } else { format!(" {code}") });
                    let orig = flat(&self.src.text[self.src.range(&sig.ident).map(|r| r.0).unwrap_or(open)..open], 70);
                    self.push("body", open, open, Tmpl::Ins(text), format!("replace body with {label}"), orig, format!("{{ return {label}; }}"));
                }
            }
        }
        self.visit_block(block);
        self.in_fn -= 1;
        self.func.pop();
    }

    fn cond_point(&mut self, c: &Expr) {
        if !self.want("cond") || self.in_fn == 0 || contains_let(c) || matches!(c, Expr::Lit(_)) {
            return;
        }
        if let Some((s, e)) = self.src.range(c) {
            let t = flat(self.snip((s, e)), 80);
            self.push("cond", s, e, Tmpl::Cond, "negate condition".into(), t.clone(), format!("!({t})"));
        }
    }
}

fn ret_values(out: &ReturnType) -> (Vec<(String, String)>, bool) {
    let v = |l: &str, c: &str| (l.to_string(), c.to_string());
    let ty = match out {
        ReturnType::Default => return (vec![v("()", "")], true),
        ReturnType::Type(_, t) => &**t,
    };
    match ty {
        Type::Tuple(t) if t.elems.is_empty() => (vec![v("()", "")], true),
        Type::Tuple(_) => (vec![v("Default::default()", "Default::default()")], false),
        Type::Path(p) if p.qself.is_none() => {
            let seg = p.path.segments.last().unwrap();
            let name = seg.ident.to_string();
            let first_arg_unit = match &seg.arguments {
                syn::PathArguments::AngleBracketed(a) => {
                    matches!(a.args.first(), Some(syn::GenericArgument::Type(Type::Tuple(t))) if t.elems.is_empty())
                }
                _ => false,
            };
            let r = match name.as_str() {
                "bool" => vec![v("true", "true"), v("false", "false")],
                "u8" | "u16" | "u32" | "u64" | "u128" | "usize" | "i8" | "i16" | "i32" | "i64" | "i128" | "isize" => {
                    vec![v("0", "0"), v("1", "1")]
                }
                "Option" => vec![v("None", "None")],
                "Result" => {
                    if first_arg_unit { vec![v("Ok(())", "Ok(())")] } else { vec![] }
                }
                "Vec" => vec![v("Vec::new()", "Vec::new()")],
                "String" => vec![v("String::new()", "String::new()")],
                "Self" | "f32" | "f64" => vec![],
                _ => vec![v("Default::default()", "Default::default()")],
            };
            (r, false)
        }
        _ => (vec![], false),
    }
}

impl<'a, 'o> Visit<'a> for Collect<'o> {
    fn visit_item_fn(&mut self, f: &'a ItemFn) {
        self.fn_like(&f.attrs, &f.sig, &f.block);
    }
    fn visit_impl_item_fn(&mut self, f: &'a ImplItemFn) {
        self.fn_like(&f.attrs, &f.sig, &f.block);
    }
    fn visit_trait_item_fn(&mut self, f: &'a syn::TraitItemFn) {
        if let Some(b) = &f.default {
            self.fn_like(&f.attrs, &f.sig, b);
        }
    }
    fn visit_item_impl(&mut self, i: &'a syn::ItemImpl) {
        if is_cfg_test(&i.attrs) {
            return;
        }
        let name = match &*i.self_ty {
            Type::Path(p) => p.path.segments.last().map(|s| s.ident.to_string()).unwrap_or_default(),
            _ => String::new(),
        };
        self.impl_ty.push(name);
        syn::visit::visit_item_impl(self, i);
        self.impl_ty.pop();
    }
    fn visit_item_mod(&mut self, m: &'a syn::ItemMod) {
        if !is_cfg_test(&m.attrs) {
            syn::visit::visit_item_mod(self, m);
        }
    }
    // Contexts that must stay constant expressions, or hold no code of interest.
    fn visit_item_const(&mut self, _: &'a syn::ItemConst) {}
    fn visit_item_static(&mut self, _: &'a syn::ItemStatic) {}
    fn visit_item_enum(&mut self, _: &'a syn::ItemEnum) {}
    fn visit_item_type(&mut self, _: &'a syn::ItemType) {}
    fn visit_impl_item_const(&mut self, _: &'a syn::ImplItemConst) {}
    fn visit_trait_item_const(&mut self, _: &'a syn::TraitItemConst) {}
    fn visit_expr_const(&mut self, _: &'a syn::ExprConst) {}
    fn visit_type(&mut self, _: &'a Type) {}
    fn visit_path(&mut self, _: &'a syn::Path) {}
    fn visit_pat(&mut self, _: &'a syn::Pat) {}
    fn visit_attribute(&mut self, _: &'a syn::Attribute) {}
    fn visit_expr_repeat(&mut self, r: &'a syn::ExprRepeat) {
        self.visit_expr(&r.expr);
    }

    fn visit_expr_if(&mut self, i: &'a syn::ExprIf) {
        self.cond_point(&i.cond);
        syn::visit::visit_expr_if(self, i);
    }
    fn visit_arm(&mut self, a: &'a syn::Arm) {
        if let Some((_, g)) = &a.guard {
            self.cond_point(g);
        }
        syn::visit::visit_arm(self, a);
    }
    fn visit_expr_lit(&mut self, l: &'a syn::ExprLit) {
        if self.in_fn > 0 && self.want("lit") {
            if let Some((s, e)) = self.src.range(l) {
                let orig = self.snip((s, e)).to_string();
                match &l.lit {
                    Lit::Int(i) => {
                        if let Ok(v) = i.base10_parse::<u128>() {
                            let new = format!("{}{}", v + 1, i.suffix());
                            self.push("lit", s, e, Tmpl::Lit(orig.clone(), new.clone()), format!("replace {orig} with {new}"), orig, new);
                        }
                    }
                    Lit::Bool(b) => {
                        let new = (!b.value).to_string();
                        self.push("lit", s, e, Tmpl::Lit(orig.clone(), new.clone()), format!("replace {orig} with {new}"), orig, new);
                    }
                    _ => {}
                }
            }
        }
    }
    fn visit_expr_binary(&mut self, b: &'a ExprBinary) {
        if self.in_fn > 0 {
            self.binary(b);
        }
        syn::visit::visit_expr_binary(self, b);
    }
}

impl<'o> Collect<'o> {
    fn binary(&mut self, b: &ExprBinary) {
        use BinOp::*;
        let (kind, orig, mutd, by_ref, assign, logic): (&'static str, &'static str, &'static str, bool, bool, bool) = match b.op {
            Add(_) => ("arith", "+", "-", false, false, false),
            Sub(_) => ("arith", "-", "+", false, false, false),
            Mul(_) => ("arith", "*", "+", false, false, false),
            Div(_) => ("arith", "/", "*", false, false, false),
            Rem(_) => ("arith", "%", "/", false, false, false),
            BitAnd(_) => ("arith", "&", "|", false, false, false),
            BitOr(_) => ("arith", "|", "&", false, false, false),
            BitXor(_) => ("arith", "^", "|", false, false, false),
            Shl(_) => ("arith", "<<", ">>", false, false, false),
            Shr(_) => ("arith", ">>", "<<", false, false, false),
            Eq(_) => ("cmp", "==", "!=", true, false, false),
            Ne(_) => ("cmp", "!=", "==", true, false, false),
            Lt(_) => ("cmp", "<", "<=", true, false, false),
            Le(_) => ("cmp", "<=", "<", true, false, false),
            Gt(_) => ("cmp", ">", ">=", true, false, false),
            Ge(_) => ("cmp", ">=", ">", true, false, false),
            And(_) => ("logic", "&&", "||", false, false, true),
            Or(_) => ("logic", "||", "&&", false, false, true),
            AddAssign(_) => ("assign", "+=", "-=", false, true, false),
            SubAssign(_) => ("assign", "-=", "+=", false, true, false),
            MulAssign(_) => ("assign", "*=", "+=", false, true, false),
            DivAssign(_) => ("assign", "/=", "*=", false, true, false),
            RemAssign(_) => ("assign", "%=", "/=", false, true, false),
            BitAndAssign(_) => ("assign", "&=", "|=", false, true, false),
            BitOrAssign(_) => ("assign", "|=", "&=", false, true, false),
            BitXorAssign(_) => ("assign", "^=", "|=", false, true, false),
            ShlAssign(_) => ("assign", "<<=", ">>=", false, true, false),
            ShrAssign(_) => ("assign", ">>=", "<<=", false, true, false),
            _ => return,
        };
        if !self.want(kind) {
            return;
        }
        let (Some(rs), Some(ra), Some(rb), Some(rop)) =
            (self.src.range(b), self.src.range(&b.left), self.src.range(&b.right), self.src.range(&b.op))
        else {
            return;
        };
        if self.snip(rop) != orig {
            return;
        }
        let (sa, sb) = (flat(self.snip(ra), 40), flat(self.snip(rb), 40));
        let orig_txt = format!("{sa} {orig} {sb}");
        let mut_txt = format!("{sa} {mutd} {sb}");
        let desc = format!("replace {orig} with {mutd}");
        if logic {
            if contains_let(&b.left) || contains_let(&b.right) || has_ctl(&b.right) {
                return;
            }
            let is_and = orig == "&&";
            self.push(kind, rs.0, rs.1, Tmpl::Logic { a: ra, b: rb, is_and }, desc, orig_txt, mut_txt);
        } else if assign {
            self.push(kind, rs.0, rs.1, Tmpl::Assign { lhs: ra, rhs: rb, orig, mutd }, desc, orig_txt, mut_txt);
        } else {
            self.push(kind, rs.0, rs.1, Tmpl::Bin { a: ra, b: rb, orig, mutd, by_ref }, desc, orig_txt, mut_txt);
        }
    }
}

