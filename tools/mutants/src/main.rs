fn arg_val(args: &[String], name: &str) -> Option<String> {
    args.iter().position(|a| a == name).and_then(|i| args.get(i + 1).cloned())
}

fn crate_root_of(root: &Path, rel: &str) -> Option<PathBuf> {
    let mut p = root.join(rel);
    while p.pop() {
        if p.join("Cargo.toml").exists() {
            return Some(p);
        }
        if p == root {
            break;
        }
    }
    None
}

fn generate(args: &[String]) -> i32 {
    let orig = PathBuf::from(arg_val(args, "--orig").expect("--orig"));
    let dest = PathBuf::from(arg_val(args, "--dest").expect("--dest"));
    let points_path = arg_val(args, "--points").expect("--points");
    let disabled: BTreeSet<u32> = arg_val(args, "--disable")
        .and_then(|p| fs::read_to_string(p).ok())
        .map(|t| t.split_whitespace().filter_map(|x| x.parse().ok()).collect())
        .unwrap_or_default();
    let kinds: BTreeSet<String> = arg_val(args, "--kinds")
        .unwrap_or_else(|| "body,arith,cmp,logic,cond,lit,assign".into())
        .split(',')
        .map(|s| s.trim().to_string())
        .collect();
    let fns: Vec<String> = arg_val(args, "--fn").map(|s| s.split(',').map(|x| x.to_string()).collect()).unwrap_or_default();
    let lines = arg_val(args, "--lines").and_then(|s| {
        let (a, b) = s.split_once('-')?;
        Some((a.parse().ok()?, b.parse().ok()?))
    });
    let opts = Opts { kinds, fns, lines };
    // Files are the trailing arguments that are not option values.
    let mut files = vec![];
    let mut i = 0;
    while i < args.len() {
        if args[i].starts_with("--") {
            i += 2;
        } else {
            files.push(args[i].clone());
            i += 1;
        }
    }
    let mut next_id = 0u32;
    let mut all: Vec<Value> = vec![];
    let mut crates: BTreeMap<PathBuf, ()> = BTreeMap::new();
    for rel in &files {
        let text = match fs::read_to_string(orig.join(rel)) {
            Ok(t) => t,
            Err(e) => {
                eprintln!("cannot read {rel}: {e}");
                return 2;
            }
        };
        let ast = match syn::parse_file(&text) {
            Ok(a) => a,
            Err(e) => {
                eprintln!("cannot parse {rel}: {e}");
                return 2;
            }
        };
        let src = Src::new(text);
        let mut c = Collect { src: &src, file: rel.clone(), o: &opts, next_id: &mut next_id, pts: vec![], func: vec![], impl_ty: vec![], in_fn: 0, skip_fn: 0 };
        let _ = c.skip_fn;
        c.visit_file(&ast);
        let pts = c.pts;
        let mut live: Vec<usize> = (0..pts.len()).filter(|&i| !disabled.contains(&pts[i].id)).collect();
        live.sort_by_key(|&i| (pts[i].s, if pts[i].s == pts[i].e { 0 } else { 1 }, std::cmp::Reverse(pts[i].e), pts[i].seq));
        let mut r = Render { src: &src.text, pts: &pts, out: String::new(), whole: HashMap::new(), glue: HashMap::new() };
        r.render(0, src.text.len(), &live);
        let d = dest.join(rel);
        fs::create_dir_all(d.parent().unwrap()).unwrap();
        let _ = fs::remove_file(&d);
        fs::write(&d, &r.out).unwrap();
        if let Some(cr) = crate_root_of(&orig, rel) {
            crates.insert(cr.strip_prefix(&orig).unwrap().to_path_buf(), ());
        }
        for p in &pts {
            all.push(json!({
                "id": p.id, "kind": p.kind, "file": p.file, "line": p.line, "col": p.col, "fn": p.func,
                "desc": p.desc, "orig": p.orig, "mutated": p.mutated, "disabled": disabled.contains(&p.id),
                "whole": r.whole.get(&p.id).cloned().unwrap_or_default(),
                "glue": r.glue.get(&p.id).cloned().unwrap_or_default(),
            }));
        }
    }
    for cr in crates.keys() {
        let sd = dest.join(cr).join("src");
        fs::write(sd.join("__mutant.rs"), RUNTIME).unwrap();
        let root = if orig.join(cr).join("src/lib.rs").exists() { "lib.rs" } else { "main.rs" };
        let t = fs::read_to_string(if sd.join(root).exists() { sd.join(root) } else { orig.join(cr).join("src").join(root) }).unwrap();
        if !t.contains("mod __mutant;") {
            let _ = fs::remove_file(sd.join(root));
            fs::write(sd.join(root), format!("{t}\n#[allow(dead_code, unused)]\nmod __mutant;\n")).unwrap();
        }
    }
    let live = all.iter().filter(|v| !v["disabled"].as_bool().unwrap()).count();
    fs::write(&points_path, serde_json::to_string_pretty(&json!({ "points": all })).unwrap()).unwrap();
    println!("{} mutation points ({} live) in {} file(s)", all.len(), live, files.len());
    0
}

fn prune(args: &[String]) -> i32 {
    let pts: Value = serde_json::from_str(&fs::read_to_string(arg_val(args, "--points").expect("--points")).unwrap()).unwrap();
    let dest = PathBuf::from(arg_val(args, "--dest").expect("--dest"));
    let dpath = arg_val(args, "--disable").expect("--disable");
    let all = args.iter().any(|a| a == "--all");
    let mut disabled: BTreeSet<u32> = fs::read_to_string(&dpath).map(|t| t.split_whitespace().filter_map(|x| x.parse().ok()).collect()).unwrap_or_default();
    let before = disabled.len();
    let prior = disabled.clone();
    let points = pts["points"].as_array().unwrap();
    let mut srcs: HashMap<String, Src> = HashMap::new();
    let input = std::io::read_to_string(std::io::stdin()).unwrap();
    let mut unmapped = vec![];
    let mut errors = 0;
    for line in input.lines() {
        let Ok(v) = serde_json::from_str::<Value>(line) else { continue };
        if v["reason"] != "compiler-message" || v["message"]["level"] != "error" {
            continue;
        }
        errors += 1;
        let mut hit = false;
        for sp in v["message"]["spans"].as_array().into_iter().flatten() {
            if sp["is_primary"] != true {
                continue;
            }
            let name = sp["file_name"].as_str().unwrap_or("");
            let rel = name.strip_prefix(&format!("{}/", dest.display())).unwrap_or(name).to_string();
            let src = srcs.entry(rel.clone()).or_insert_with(|| Src::new(fs::read_to_string(dest.join(&rel)).unwrap_or_default()));
            if src.text.is_empty() {
                continue;
            }
            let ls = sp["line_start"].as_u64().unwrap_or(1) as usize;
            let cs = sp["column_start"].as_u64().unwrap_or(1) as usize;
            let off = src.off(LineColumn { line: ls, column: cs - 1 });
            let in_r = |v: &Value, k: &str| v[k].as_array().into_iter().flatten().any(|r| r[0].as_u64().unwrap() as usize <= off && off < r[1].as_u64().unwrap() as usize);
            let here: Vec<&Value> = points.iter().filter(|p| p["file"] == rel.as_str() && p["disabled"] == false && !prior.contains(&(p["id"].as_u64().unwrap() as u32))).collect();
            let glue: Vec<&&Value> = here.iter().filter(|p| in_r(p, "glue")).collect();
            if let Some(p) = glue.first() {
                disabled.insert(p["id"].as_u64().unwrap() as u32);
                hit = true;
                continue;
            }
            let mut enclosing: Vec<&&Value> = here.iter().filter(|p| in_r(p, "whole")).collect();
            // innermost = smallest whole range containing the offset
            enclosing.sort_by_key(|p| p["whole"].as_array().unwrap().iter().filter(|r| r[0].as_u64().unwrap() as usize <= off && off < r[1].as_u64().unwrap() as usize).map(|r| r[1].as_u64().unwrap() - r[0].as_u64().unwrap()).min().unwrap_or(u64::MAX));
            let take = if all { enclosing.len() } else { 1.min(enclosing.len()) };
            for p in enclosing.iter().take(take) {
                disabled.insert(p["id"].as_u64().unwrap() as u32);
                hit = true;
            }
        }
        if !hit {
            unmapped.push(v["message"]["rendered"].as_str().unwrap_or("").lines().take(3).collect::<Vec<_>>().join("\n"));
        }
    }
    fs::write(&dpath, disabled.iter().map(|d| d.to_string()).collect::<Vec<_>>().join("\n")).unwrap();
    println!("{errors} compile errors, {} mutation points disabled this round ({} in total)", disabled.len() - before, disabled.len());
    for u in unmapped.iter().take(5) {
        eprintln!("unmapped error: {u}");
    }
    if disabled.len() > before { 0 } else { 3 }
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let code = match args.first().map(String::as_str) {
        Some("gen") => generate(&args[1..]),
        Some("prune") => prune(&args[1..]),
        _ => {
            eprintln!("usage: ti4-mutants gen|prune ... (see the header of src/main.rs)");
            2
        }
    };
    std::process::exit(code);
}
