struct Render<'a> {
    src: &'a str,
    pts: &'a [Point],
    out: String,
    whole: HashMap<u32, Vec<(usize, usize)>>,
    glue: HashMap<u32, Vec<(usize, usize)>>,
}

fn newlines(s: &str) -> String {
    "\n".repeat(s.matches('\n').count())
}

impl<'a> Render<'a> {
    fn emit(&mut self, id: u32, t: &str) {
        let s = self.out.len();
        self.out.push_str(t);
        self.glue.entry(id).or_default().push((s, self.out.len()));
    }
    fn sub(&mut self, r: (usize, usize), nested: &[usize]) {
        let pts = self.pts;
        let inside: Vec<usize> = nested.iter().copied().filter(|&i| pts[i].s >= r.0 && pts[i].e <= r.1).collect();
        self.render(r.0, r.1, &inside);
    }
    fn render(&mut self, s: usize, e: usize, idxs: &[usize]) {
        let pts = self.pts;
        let src = self.src;
        let mut cur = s;
        let mut i = 0;
        while i < idxs.len() {
            let p = &pts[idxs[i]];
            self.out.push_str(&src[cur..p.s]);
            if p.s == p.e {
                if let Tmpl::Ins(t) = &p.tmpl {
                    self.emit(p.id, t);
                }
                cur = p.s;
                i += 1;
                continue;
            }
            let mut j = i + 1;
            while j < idxs.len() {
                let q = &pts[idxs[j]];
                if q.s >= p.s && q.e <= p.e && q.s < p.e { j += 1 } else { break }
            }
            let nested = &idxs[i + 1..j];
            let w0 = self.out.len();
            let id = p.id;
            match &p.tmpl {
                Tmpl::Bin { a, b, orig, mutd, by_ref } => {
                    let r = if *by_ref { "&" } else { "" };
                    self.emit(id, &format!("(match ({r}"));
                    self.sub(*a, nested);
                    let gap = newlines(&src[a.1..b.0]);
                    self.emit(id, &format!(", {r}{gap}"));
                    self.sub(*b, nested);
                    self.emit(id, &format!(") {{ (__l, __r) => if {RT}::on({id}) {{ __l {mutd} __r }} else {{ __l {orig} __r }} }})"));
                }
                Tmpl::Assign { lhs, rhs, orig, mutd } => {
                    let gap = newlines(&src[lhs.1..rhs.0]);
                    self.emit(id, "(match ");
                    self.sub(*rhs, nested);
                    self.emit(id, &format!(" {{ __r => if {RT}::on({id}) {{ {gap}"));
                    self.sub(*lhs, nested);
                    self.emit(id, &format!(" {mutd} __r }} else {{ "));
                    self.sub(*lhs, nested);
                    self.emit(id, &format!(" {orig} __r }} }})"));
                }
                Tmpl::Logic { a, b, is_and } => {
                    let f = if *is_and { "and" } else { "or" };
                    self.emit(id, &format!("({RT}::{f}({id}, "));
                    self.sub(*a, nested);
                    let gap = newlines(&src[a.1..b.0]);
                    self.emit(id, &format!(", {gap}|| "));
                    self.sub(*b, nested);
                    self.emit(id, "))");
                }
                Tmpl::Cond => {
                    self.emit(id, &format!("{RT}::not({id}, "));
                    self.sub((p.s, p.e), nested);
                    self.emit(id, ")");
                }
                Tmpl::Lit(o, n) => {
                    self.emit(id, &format!("(if {RT}::on({id}) {{ {n} }} else {{ {o} }})"));
                }
                Tmpl::Ins(_) => {}
            }
            self.whole.entry(id).or_default().push((w0, self.out.len()));
            cur = p.e;
            i = j;
        }
        self.out.push_str(&src[cur..e]);
    }
}

